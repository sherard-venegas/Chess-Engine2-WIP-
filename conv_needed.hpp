//turns the lsb to an index using a debruijn sequence
int get_lsb_ind(uint64_t board){
	uint64_t lsb_val = board ^ (board - 1);
	unsigned int fold = (unsigned)( (lsb_val & 0xffffffff) ^ (lsb_val >> 32));
	return BitTable[(fold * 0x783a9b23) >> 26]; // uses perfect hashing to find the specific position of the LSB
}

void print_board(uint64_t num){
    uint64_t com = 1;
    int i = 0;
    uint64_t bor = num;
    while( i < 64){
        uint64_t res = (com & bor);
        if(res){ cout << " 1 "; }
        else{ cout << " 0 "; }
        if(i % 8 == 7){ cout << "\n"; }
        i++;
        com = (com << 1);
    }
}

uint64_t north_fill(uint64_t board){
    board |= (board >> 8);
    board |= (board >> 16);
    board |= (board >> 32);
    return board;
}

uint64_t south_fill(uint64_t board){
    board |= (board << 8);
    board |= (board << 16);
    board |= (board << 32);
    return board;
}